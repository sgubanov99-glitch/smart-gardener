const FAMILIES = {
  'томат':'паслёновые','перец':'паслёновые','баклажан':'паслёновые','картофель':'паслёновые',
  'огурец':'тыквенные','кабачок':'тыквенные','тыква':'тыквенные','патиссон':'тыквенные','дыня':'тыквенные','арбуз':'тыквенные',
  'капуста':'крестоцветные','редис':'крестоцветные','репа':'крестоцветные','рукола':'крестоцветные',
  'горох':'бобовые','фасоль':'бобовые',
  'морковь':'зонтичные','укроп':'зонтичные','петрушка':'зонтичные','кинза':'зонтичные',
  'свёкла':'амарантовые','шпинат':'амарантовые',
  'лук':'амариллисовые','чеснок':'амариллисовые',
  'салат':'астровые',
  'щавель':'гречишные',
  'клубника':'розовые','земляника садовая':'розовые'
};

const GOOD = [
  ['морковь','лук'],['морковь','горох'],['огурец','горох'],['огурец','фасоль'],
  ['клубника','лук'],['клубника','чеснок'],['капуста','салат'],['томат','петрушка'],['свёкла','лук']
];
const BAD = [
  ['томат','картофель'],['томат','огурец'],['лук','горох'],['лук','фасоль'],
  ['чеснок','горох'],['чеснок','фасоль'],['морковь','укроп'],['морковь','петрушка'],
  ['капуста','клубника'],['огурец','картофель']
];

export async function loadCompatibility(){
  return { families: FAMILIES, good: GOOD, bad: BAD };
}

export function familyOf(compat, crop){
  if(!compat || !crop) return null;
  return compat.families[String(crop).trim().toLowerCase()] || null;
}

export function pairResult(compat, a, b){
  if(!compat || !a || !b) return null;
  const x = String(a).trim().toLowerCase(), y = String(b).trim().toLowerCase();
  if (x === y) return null;
  const has = (list) => (list||[]).some(p => (p[0]===x && p[1]===y) || (p[0]===y && p[1]===x));
  if (has(compat.bad)) return 'bad';
  if (has(compat.good)) return 'good';
  return null;
}